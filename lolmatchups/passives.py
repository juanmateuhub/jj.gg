"""Tabla de pasivas de los campeones para el modelo teórico de duelo.

Cada campeón tiene:
  status  -> "modelada"          : sus efectos de combate están representados.
             "aproximada"        : representada con simplificaciones (ver nota).
             "sin_efecto_duelo"  : la pasiva no influye en un duelo 1v1 en calle (movilidad, oro, visión...).
             "no_modelada"       : influye, pero su mecánica no es representable en el simulador.
  note    -> explicación breve.
  effects -> lista de efectos (ver theory.py para su interpretación).

Los valores escritos como (a, b) escalan con el nivel del campeón: a en nivel 1 y b en nivel 18.
Los valores proceden de las descripciones de Meraki Analytics; revísalos si un parche los cambia.

Tipos de efecto:
  on_hit        daño adicional en ataques básicos (opcional: cooldown, once, target_below)
  proc          daño cada N golpes (source: attack / ability / any)
  after_ability los N siguientes ataques tras lanzar una habilidad obtienen bonus
  dot           daño por acumulación aplicado con cada golpe (sangrados, venenos)
  ramp          acumulaciones que dan velocidad de ataque y un efecto al máximo (at_max)
  stats         estadísticas planas (AD, AS, armadura, robo de vida, reducción de daño, multiplicador de ataques...)
  shield        escudo (trigger: start / low_hp / after_ability / on_attack)
  heal          curación periódica (trigger: after_ability / attack)
  regen         regeneración en combate
  missing_hp    bonus que crece con la vida perdida (Olaf)
"""

